export const getSortedProjects = (items: Project[] = projects) =>
  [...items].sort((a, b) => a.order - b.order || b.year.localeCompare(a.year));

export const getFeaturedProjects = () => getSortedProjects(projects.filter((project) => project.isFeatured));

export const getProjectsByCategory = (category: ProjectCategory) =>
  getSortedProjects(projects.filter((project) => project.category === category));

export const getProjectById = (id: string | undefined) =>
  projects.find((project) => project.id === id);
